export function Gfx_generate_context(FLAGS, mesh, spesific_gfx_idxs = [INT_NULL, null]) {


   // Cash
   const sid = mesh.sid;
   const sceneidx = mesh.sceneidx;
   const mesh_count = mesh.geom.num_faces;
   const root_bufferidx = mesh.root_bufferidx;
   const mesh_bufferidx = mesh.mesh_bufferidx;
   const uniforms = mesh.uniforms;


   let progidx = INT_NULL;
   let ibidx = INT_NULL;
   let vb_group = null;
   let vbidxs = null;
   
   
   // Check buffers validity, or find buffers based on Flags
   const igfx = Find_gfx_match_from_mesh_tree(FLAGS, mesh, spesific_gfx_idxs);
   progidx = igfx[0];
   let vb_groupidx = igfx[1];
   if(vb_groupidx !== INT_NULL) // Get the vbidxs if an apropriate vb group is found
      vbidxs = Vertex_buffer_group_get_vbidxs(vb_groupidx);





   /*******************************************************************************************************************/
   // Program

   // Check if program already exists
   progidx = Program_program_exists_from_sid(sid);

   if (progidx === INT_NULL) { // If shader program does not exist, create new program.

      progidx = Program_create_program(sid, uniforms);

      Scene_set_projection_matrix(sceneidx)

      // HACK: the uniform block should not be implemented HERE, Also weather or not the 'u_screen_res' should be enabled is responsibility of 'WHO'???????????????????
      const unifidx = Uniforms_block_bind_uniform_layout('u_screen_res');
      Uniforms_block_set_uniform(unifidx, [VIEWPORT.WIDTH, VIEWPORT.HEIGHT]);


      /**
       * Here we connect each mesh uniform index 'ubidx', with the ubidx from the uniforms buffer.
       */
      for (let i = 0; i < uniforms.length; i++) {

         if ((uniforms[i].shader & UNIFORM.IS_SHARED) === 0) {

            const ubidx = Uniforms_buffer_find_ubidx_from_name(uniforms[i].name);
            Mesh_set_uniform_ubidx_from_name(uniforms, ubidx, uniforms[i].name);
            // mesh.SetUniformIndex(ubidx, uniforms[i].name)
            Uniforms_buffer_set_uniform(ubidx, [mesh.geom.pos[0], mesh.geom.pos[1]]);
            Uniforms_buffer_update_uniform(ubidx);
            // console.warn(ubidx, uniforms[i].name, mesh.GetName())
         }

      }


   }



   /*******************************************************************************************************************/
   // Vertex buffer

   let is_vertex_buffer_created = false;

   const pool_request_flags = mesh.gfx_pool_request;

   if (vb_groupidx === INT_NULL) {

      // First look a the gfx pool for any matching vertex buffer
      vb_groupidx = Gfx_pool_find_vb_notActive_and_private(sid, pool_request_flags);

      if (vb_groupidx === INT_NULL) {

         vb_group = Vertex_buffer_create(sid, _, progidx); 
         vb_groupidx = vb_group.idx;
         vbidxs = Vertex_buffer_group_get_vbidxs(vb_groupidx);


         // Vertex_buffer_group_state_enable(vb_groupidx, BUFFER_STATE.IS_PRIVATE);
         if (DEBUG.GFX.CONTEXT_CREATE) console.log('NO BUFFER FOUND. CREATE NEW VB ############', progidx, vbidxs);

         // Program_store_vertex_buffer_group_idx(progidx, vbidx, vb_info.vao, vb_info.vaoidx); // Store the vertexbuffer index to the programs vb array  

         // Create Gfx Buffer buffer. It will be created at the 'vbidx' index.
         Mesh_per_vb_create_vb(vb_groupidx);

         is_vertex_buffer_created = true;

      }

   }





   /*******************************************************************************************************************/
   // Index buffer

   if (sid.shad & SID.SHAD.INDEXED) {

      // IMPORTANT: WHO IS RESPONSIBLE OF DECIDING THE INDEX BUFFER PATTERN ?????????????
      ibidx = Gfx_pool_find_ib_notActive(TEMPORARY_INDEX_BUFFER_RECOGNITION_PATTERN.rect_123_234); // HACK: At this point we just pass the only usable of the app, index buffer pattern

      if (ibidx === INT_NULL) { // Create new index buffer

         const ib_info = Index_buffer_info_create(sid, _, TEMPORARY_INDEX_BUFFER_RECOGNITION_PATTERN.rect_123_234);
         ibidx = ib_info.ibidx;

         Program_store_index_buffer_idx(progidx, ibidx); // Store the indexbuffer index to the programs ib array

      }

   }


   if (is_vertex_buffer_created) {

      // Add the new vertexBuffer to the render queue
      Renderqueue_Add(progidx, vb_groupidx, ibidx, true);
      Renderqueue_set_active(vb_groupidx, true); // Update the draw buffer


      
      Widget_root_gfx_add(root_bufferidx, mesh_bufferidx, progidx, vb_groupidx, vbidxs);
      Vertex_buffer_group_set_ibidx(vb_groupidx, ibidx); // Create a refference of ib to vb


      // UNNECESSARY: For all vb except the widget root. All the root wpos are set from a function call, based on the root root_wpos 

      const root_posidx = Mesh_unif_create_vb_root_wpos(mesh.mesh_bufferidx, mesh.geom.pos, mesh.type, mesh.nameidx, mesh.parent, vb_groupidx);
      mesh.root_posidx = root_posidx;
      if (root_posidx !== vb_groupidx) alert('root_posidx is NOT equal to vbidx');


      /**
       * Here we connect each mesh uniform index 'ubidx', with the ubidx from the uniforms buffer.
       */
      for (let i = 0; i < uniforms.length; i++) {

         if ((uniforms[i].shader & UNIFORM.IS_SHARED) === 0) {

            const ubidx = uniforms[i].ubidx
            // if has unif u_col, create uunif col root
            Mesh_unif_create_vb_root_col(mesh.mat.col)
            console.warn(ubidx, uniforms[i].name, mesh.GetName())
         }

      }



   }

   // TODO: Implement
   // // Add mesh to the root batch buffer for batch update
   // Widget_root_batch_assign_and_accum_to_vb(root_bufferidx, mesh_bufferidx, progidx, vbidx, mesh_count);


   // Store the root pos in each mesh. Assuumes the indexing of root_wpos and vbs are 1-1.
   mesh.root_posidx = vb_groupidx;



   const gfx = Generate_mesh_gfx_info(sid, sceneidx, progidx, vb_groupidx, ibidx, mesh_count);
   return gfx;


}




export function TEMP_Gfx_generate_context_for_particles(FLAGS, emitter, gfx_pool_request) {


   // Cash
   const sid = emitter.sid;
   const sceneidx = emitter.sceneidx;
   const uniforms = emitter.uniforms;


   let progidx = INT_NULL;
   let vbidx = INT_NULL;
   let ibidx = INT_NULL;




   /*******************************************************************************************************************/
   // Program

   // Check if program already exists
   progidx = Program_program_exists_from_sid(sid);

   if (progidx === INT_NULL) { // If shader program does not exist, create new program.

      progidx = Program_create_program(sid, uniforms);

      Scene_set_projection_matrix(sceneidx)

      // HACK: the uniform block should not be implemented HERE, Also weather or not the 'u_screen_res' should be enabled is responsibility of 'WHO'???????????????????
      const unifidx = Uniforms_block_bind_uniform_layout('u_screen_res');
      Uniforms_block_set_uniform(unifidx, [VIEWPORT.WIDTH, VIEWPORT.HEIGHT]);


      /**
       * Here we connect each mesh uniform index 'ubidx', with the ubidx from the uniforms buffer.
       */
      for (let i = 0; i < uniforms.length; i++) {

         if ((uniforms[i].shader & UNIFORM.IS_SHARED) === 0) {

            const ubidx = Uniforms_buffer_find_ubidx_from_name(uniforms[i].name)
            Mesh_set_uniform_ubidx_from_name(uniforms, ubidx, uniforms[i].name);
            Uniforms_buffer_set_uniform(ubidx, [emitter.pos[0], emitter.pos[1]]);
            Uniforms_buffer_update_uniform(ubidx);
            // console.warn(ubidx, uniforms[i].name, mesh.GetName())
         }

      }


   }



   /*******************************************************************************************************************/
   // Vertex buffer

   let is_vertex_buffer_created = false;

   const pool_request_flags = gfx_pool_request;

   if (vbidx === INT_NULL) {

      // First look at the gfx pool for any matching vertex buffer
      vbidx = Gfx_pool_find_vb_notActive_and_private(sid, pool_request_flags);

      if (vbidx === INT_NULL) {

         const vb_info = Vertex_buffer_create(sid, _, progidx);
         vbidx = vb_info.vbidx;


         // Vertex_buffer_state_enable(vbidx, BUFFER_STATE.IS_PRIVATE | BUFFER_STATE.SHOW);
         // Vertex_buffer_state_enable(vbidx, BUFFER_STATE.IS_PRIVATE);
         if (DEBUG.GFX.CONTEXT_CREATE) console.log('NO BUFFER FOUND. CREATE NEW VB ############', progidx, vbidx);

         Program_store_vertex_buffer_group_idx(progidx, vbidx, vb_info.vao, vb_info.vaoidx); // Store the vertexbuffer index to the programs vb array

         // Create Gfx Buffer buffer. It will be created at the 'vbidx' index.
         Mesh_per_vb_create_vb(vbidx);

         is_vertex_buffer_created = true;

      }

   }





   /*******************************************************************************************************************/
   // Index buffer

   if (sid.shad & SID.SHAD.INDEXED) {

      ibidx = Gfx_pool_find_ib_notActive(TEMPORARY_INDEX_BUFFER_RECOGNITION_PATTERN.rect_123_234);

      if (ibidx === INT_NULL) { // Create new index buffer

         const ib_info = Index_buffer_info_create(sid, _, TEMPORARY_INDEX_BUFFER_RECOGNITION_PATTERN.rect_123_234);
         ibidx = ib_info.ibidx;

         Program_store_index_buffer_idx(progidx, ibidx); // Store the indexbuffer index to the programs ib array

      }

   }


   if (is_vertex_buffer_created) {

      // Add the new vertexBuffer to the render queue
      Renderqueue_Add(progidx, vb_groupidx, ibidx, true);
      Renderqueue_set_active(vb_groupidx, true); // Update the draw buffer

      Vertex_buffer_group_set_ibidx(vb_groupidx, ibidx); // Create a refference of ib to vb

      // mesh_bufferidx, mesh_pos, mesh_type, mesh_nameidx, mesh_parent=null, debug_vbidx
      const root_posidx = Mesh_unif_create_vb_root_wpos(INT_NULL, emitter.pos, emitter.type, emitter.nameidx, null, vb_groupidx);
      emitter.root_posidx = root_posidx;

      
      /**
       * Here we connect each mesh uniform index 'ubidx', with the ubidx from the uniforms buffer.
       */
      for (let i = 0; i < uniforms.length; i++) {

         if ((uniforms[i].shader & UNIFORM.IS_SHARED) === 0) {

            const ubidx = uniforms[i].ubidx
            // if has unif u_col, create uunif col root
            Mesh_unif_create_vb_root_col(emitter.col)
            // console.warn(ubidx, uniforms[i].name, emitter.GetName())
         }

      }

      if (root_posidx !== vbidx) alert('root_posidx is NOT equal to vbidx');
   }




   // Store the root pos in each mesh. Assuumes the indexing of root_wpos and vbs are 1-1.
   emitter.root_posidx = vbidx;



   const gfx = Generate_mesh_gfx_info(sid, sceneidx, progidx, vbidx, ibidx);

   return gfx;


}












